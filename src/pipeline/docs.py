"""docs/data/gold_tables.md: column-level schemas of the gold tables (INTERFACES.md #5), generated from
the Parquet files so the document never drifts from the data. Run by ``make pipeline``."""

from __future__ import annotations

import duckdb

from pipeline import config, gold

TABLE_DOCS = {
    "customer_profile": "Server-side profile (session, G1 context, gateway `get_customer_profile`). First name only; no document, e-mail, phone or address. `reference_date` = latest transaction on or before the cut-off.",
    "customer_products": "Products of each customer (gateway `get_cards`, M1 card last 4). Only the last 4 digits of any number.",
    "transactions_enriched": "Transactions as on the statement (gateway, M1, M3, G2). `local_date`/`local_time` from `ts`; `process_date` is the accounting date. `is_fraud` is a label for M3/evaluation only, never served.",
    "fee_schedule": "SYNTHETIC fee schedule per product (the dataset has none). Team assumption, labelled `synthetic`.",
    "fee_charges": "SYNTHETIC monthly fee charges that match `fee_schedule` (last 6 months); same columns as `transactions_enriched`, `origin = synthetic_fee`.",
    "customer_baseline": "Usual behaviour per customer from purchases older than 14 days before the reference date (365-day window).",
    "customer_category_baseline": "Per customer and category: count, median and p95 in USD (same window).",
    "merchant_stats": "Aggregates per merchant across the bank (never another customer's records).",
    "complaints_baseline": "Historical complaint times per v2 complaint type (promise clock, baseline B0).",
    "contact_history": "Formal complaints (`complaint`) and call-center contacts (`inquiry`) per customer: real repeat history.",
    "digital_sessions": "Digital-banking sessions per customer (logins, first time on a device) for G2 and M3.",
    "kpi_baseline": "B0 historical baseline, one row per metric (evaluation report and page).",
    "cc_category_baseline": "Call-center baseline per contact reason (v1.4): volume, first-contact resolution, duration, CSAT, estimated cost.",
    "labels": "Learning-loop labels (analyst decisions and outcomes); union of `data/labels/*.parquet`.",
}


def write() -> str:
    meta = gold.read_meta()
    con = duckdb.connect()
    lines = ["# Gold tables (INTERFACES.md #5)", "",
             "Generated by `make pipeline` (`src/pipeline/docs.py`) from the Parquet files in `data/gold/<table>/`. "
             "SQL: `src/pipeline/sql/gold/<table>.sql`. Never edit by hand.", "",
             f"Data source of the last build: **{meta.get('data_source', '?')}** · snapshot {meta.get('snapshot_date', '?')} · "
             f"built {meta.get('built_at', '?')}.", "",
             "Serving export for DynamoDB (`pipeline/serving.py`): pk `CUST#<customer_id>`, sk `PROFILE | PRODUCT#<id> | "
             "TXN#<local_date>#<txn_id> | BASELINE | CATBASE#<category> | FEE#<product_id>#<fee_code> | CONTACT#<date>#<id>`; "
             "merchant aggregates under `MERCHANT#<merchant_id>` / `STATS`. `is_fraud` is never exported.", ""]
    for t in config.GOLD_ORDER:
        f = config.GOLD_DIR / t / "data.parquet"
        lines += [f"## {t}", "", TABLE_DOCS.get(t, ""), ""]
        if not f.exists():
            lines += ["(not built)", ""]
            continue
        rows = con.execute(f"DESCRIBE SELECT * FROM read_parquet('{f.as_posix()}')").fetchall()
        n = (meta.get("rows") or {}).get(t)
        lines += [f"Rows in the last build: {n:,}" if isinstance(n, int) else "", "", "| Column | Type |", "|---|---|"]
        lines += [f"| `{r[0]}` | {r[1]} |" for r in rows]
        lines.append("")
    con.close()
    config.DOCS_DATA_DIR.mkdir(parents=True, exist_ok=True)
    out = config.DOCS_DATA_DIR / "gold_tables.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(out)
