// ---------- POST /chat ----------
// At most one of message or button_id. A request with neither is valid only when it carries
// demo_switches (a "switches only" request, see DemoSwitchesPatch).
export interface ChatRequest {
  client_msg_id: string; // uuid generated by the client; same id = same answer, never a second case
  message?: string; // max 1000 characters
  button_id?: string; // opaque id issued by the server in a previous turn
  demo_switches?: DemoSwitchesPatch; // judge-mode failure switches (RF-22), applied server side
}

// Failure switches of the judge mode (RF-22, plan section 12). They belong to the session and
// hold from the request that carries them (applied before its message or button).
// - Only the keys present change; at least one key must be present.
// - expire_session: true ends the session at once: this request and every later one answer
//   401 session_expired (a message or button in the same request is not processed).
//   expire_session: false is a no-op.
// - Switches only (no message, no button_id): the server answers a short template
//   ChatResponse confirming the switch WITHOUT advancing the conversation: `turn` repeats the
//   last turn number (it does not count toward the 30-turn cap), `buttons` is [] while the
//   buttons already pending stay valid (the UI keeps showing them), progress, case_card and
//   lane are the current ones, degraded is [], trace_summary has one rule step "demo_switches".
export interface DemoSwitchesPatch {
  tools_down?: boolean; // every gateway tool fails -> two retries, then lane C tool_failure
  model_slow?: boolean; // G1 exceeds LLM_TIMEOUT_SECONDS -> template reply, degraded model_timeout
  expire_session?: boolean; // true: the session expires now (401 session_expired)
  // Demo clock: the SLA timers of this session's lane B cases run 1440 times faster (1 day =
  // 1 minute; `local_api.py --sla-scale` changes the factor). Applies to the case already
  // open in the session and to the ones it opens later, never to other sessions. Promised
  // dates (expected_date, first_response_by) do not change. Does not exist in production.
  fast_clock?: boolean;
}

// Switch state of the session, echoed in every ChatResponse.
export interface DemoSwitchState {
  tools_down: boolean;
  model_slow: boolean;
  fast_clock: boolean;
}

