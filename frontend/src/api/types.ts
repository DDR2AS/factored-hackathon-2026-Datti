// Customer-facing step of the lane B lifecycle (the card's "Investigando -> En revisión ->
// Notificado"). Derived from status by customer_view; null outside lane B.
// open|reopened -> open, investigating -> investigating, awaiting_analyst -> in_review,
// handed_off in lane B (analyst escalated) -> in_review, notified -> notified, closed -> closed.
export type LifecycleStep = "open" | "investigating" | "in_review" | "notified" | "closed";

// The reply the customer receives after an analyst decided. Only a person approves it:
