// SLA timers of a lane B case (plan v2 sections 6 and 12), scheduled when the case opens and
// deleted when an analyst decides; they only fire while the case is still open (open,
// investigating, awaiting_analyst):
// - unassigned: clock.assigned_by (+24 h) and no analyst took the case (opened it in the
//   console or decided it) -> alert in the analyst queue (sla_alerts)
// - sla_80: clock.sla_alert_at (80 % of the SLA) -> proactive notice to the customer
// - breached: clock.breach_at -> automatic escalation to the senior queue, priority high,
//   and a notice to the customer
export type SlaTimerKind = "unassigned" | "sla_80" | "breached";
export type NoticeKind = "sla_80" | "escalated";

