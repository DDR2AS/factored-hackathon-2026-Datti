// ---------- POST /analyst/cases/{case_id}/decision ----------
// - approve: sends report.draft_reply as is. No reply, no next. Needs a report with a draft.
// - edit: sends `reply` instead of the draft. reply and reason are required; no next.
// - reject: the recommendation is rejected. reason and next are required. reply is optional
//   and only with next=request_information (the question sent to the customer; without it
//   the server uses the request_information template); with escalate nothing is sent.
// - Every field outside these rules is a 400 invalid_request (e.g. approve with reply).
// - evidence_reviewed: must be true to approve or edit when the report is unreliable.
// - Stale version, or a second decision on an already decided case -> 409 conflict. The same
//   client_decision_id with the same body returns the stored DecisionResponse (safe retry).
// - Case not awaiting_analyst, approve without a draft, reply.language != case language,
//   unreliable report without evidence_reviewed -> 422 precondition.
export interface DecisionReply {
  language: Language;
  text: string; // 1..2000 characters
}

export interface DecisionLabels {
  intent_class?: IntentClass; // correction of the predicted class
  intent_confirmed?: boolean; // true: the predicted class is right (then no intent_class)
}

